import {chromium} from 'playwright-core';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const root=process.cwd();
const runtime=JSON.parse(await fs.readFile(`${root}/outputs/AsciiCity-Wallpaper/data/runtime.json`,'utf8'));
const headers={Authorization:`Bearer ${runtime.token}`};
const status=async()=>{const response=await fetch(`http://127.0.0.1:${runtime.port}/status`,{headers});return response.json();};
const browser=await chromium.connectOverCDP('http://127.0.0.1:9223');
const page=browser.contexts().flatMap(c=>c.pages()).find(p=>p.url().includes('tauri.localhost'));
assert.ok(page,'Native WebView was not found');
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await fs.mkdir(`${root}/artifacts/native`,{recursive:true});
try {
  await page.waitForFunction(()=>Boolean(window.asciiCity));
  const origin=await page.evaluate(()=>performance.timeOrigin);
  assert.equal(await page.locator('#nogl').isVisible(),false);
  const initial=await status();assert.ok(initial.parent!==0);assert.equal(initial.metrics.rejectedEvents,0);
  await page.evaluate(()=>window.__TAURI__.core.invoke('host_command',{command:'interactive'}));
  await page.waitForFunction(()=>document.body.classList.contains('live'));
  await page.waitForTimeout(1000);
  await page.screenshot({path:`${root}/artifacts/native/control.png`});
  const record=await page.evaluate(()=>window.asciiCity.export());
  assert.ok(record.includes('sys.sample'));assert.ok(record.includes('audio.frame'));
  assert.doesNotMatch(record,/demo-claude|demo-codex|城市电台/);
  await page.locator('#privacyChk').check();await page.waitForTimeout(250);
  assert.equal((await status()).config.privacy,true);
  await page.locator('#privacyChk').uncheck();
  const before=await status();const config=structuredClone(before.config);config.pauseWhenCovered=false;
  await page.evaluate(config=>window.__TAURI__.core.invoke('host_config',{config}),config);
  await page.evaluate(()=>window.__TAURI__.core.invoke('host_command',{command:'wallpaper'}));
  await page.waitForFunction(()=>document.body.classList.contains('wallpaper'));await page.waitForTimeout(1500);
  await page.screenshot({path:`${root}/artifacts/native/wallpaper.png`});
  const wallpaper=await status();assert.ok(wallpaper.parent!==0);assert.equal(wallpaper.mode,'wallpaper');
  await page.evaluate(()=>window.__TAURI__.core.invoke('host_command',{command:'pause'}));await page.waitForTimeout(2200);
  const paused=await status();assert.equal(paused.paused,true);assert.equal(paused.metrics.fps,0);
  await page.evaluate(()=>window.__TAURI__.core.invoke('host_command',{command:'resume'}));
  await page.evaluate(config=>window.__TAURI__.core.invoke('host_config',{config}),before.config);
  assert.equal(await page.evaluate(()=>performance.timeOrigin),origin,'Mode changes reloaded the world');
  assert.deepEqual(errors,[]);const final=await status();
  await fs.writeFile(`${root}/artifacts/native/integration-report.json`,JSON.stringify({initial,wallpaper,paused,final,errors,worldReloaded:false},null,2));
  console.log(JSON.stringify({sources:final.sources,counters:final.counters,parent:final.parent,errors,worldReloaded:false},null,2));process.exit(0);
}catch(error){console.error(error);process.exit(1);}
