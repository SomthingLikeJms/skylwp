import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';

// Supply Windows-filtered `cargo metadata --locked --format-version 1` output.
const metadataFile = process.argv[2];
if (!metadataFile) throw new Error('Usage: node tools/collect-licenses.mjs <cargo-metadata.json>');
const metadata = JSON.parse((await fs.readFile(metadataFile, 'utf8')).replace(/^\uFEFF/, ''));
const nodes = new Map(metadata.resolve.nodes.map((n) => [n.id, n]));
const used = new Set();
function visit(id) {
  if (used.has(id)) return;
  used.add(id);
  for (const dependency of nodes.get(id)?.dependencies ?? []) visit(dependency);
}
visit(metadata.resolve.root);
const packages = metadata.packages
  .filter((p) => used.has(p.id) && p.source)
  .sort((a, b) => `${a.name}@${a.version}`.localeCompare(`${b.name}@${b.version}`, 'en'));
const byName = new Map(packages.map((p) => [p.name, p]));
const texts = new Map();
const components = [];
async function addText(file) {
  const text = (await fs.readFile(file, 'utf8')).replace(/\r\n/g, '\n').trim();
  const hash = createHash('sha256').update(text).digest('hex');
  if (!texts.has(hash)) texts.set(hash, text);
  return hash;
}
async function licenseFiles(dir) {
  return (await fs.readdir(dir, { withFileTypes: true }))
    .filter(
      (f) => f.isFile() && /^(?:LICEN[CS]E|COPYING|NOTICE|COPYRIGHT)(?:$|[._-])/i.test(f.name),
    )
    .map((f) => path.join(dir, f.name))
    .sort();
}
// These workspace crates omit the common upstream license in their crate archive.
// Reuse that upstream's license text, not a generated generic license template.
const shared = {
  'alloc-stdlib': 'alloc-no-stdlib',
  'tauri-plugin': 'tauri',
  'winapi-x86_64-pc-windows-gnu': 'winapi',
  selectors: 'cssparser',
};
for (const p of packages) {
  const dir = path.dirname(p.manifest_path);
  let files = await licenseFiles(dir),
    note = '';
  if (p.license_file) files.push(path.resolve(dir, p.license_file));
  if (!files.length && shared[p.name]) {
    const source = byName.get(shared[p.name]);
    files = await licenseFiles(path.dirname(source.manifest_path));
    note =
      p.name === 'selectors'
        ? 'MPL-2.0 text shared with cssparser; selectors source carries the same MPL-2.0 notice.'
        : `Shared upstream license supplied by ${source.name} ${source.version}.`;
  }
  if (!files.length && p.name.startsWith('webview2-com')) {
    files = ['docs/licenses/webview2-rs-LICENSE.txt'];
    note =
      'Upstream LICENSE verified at edc2caf886175ccaebe86078c9cfe1ae2a187328 and dffa41a8a46d3f5565eefbff2de57d38d399f158.';
  }
  if (!files.length) throw new Error(`Missing license text: ${p.name} ${p.version}`);
  components.push({
    name: `${p.name} ${p.version}`,
    license: p.license,
    repository: p.repository,
    source: `https://crates.io/api/v1/crates/${p.name}/${p.version}/download`,
    note,
    texts: await Promise.all([...new Set(files)].map(addText)),
  });
}
const npmDir = 'node_modules/get-east-asian-width';
const npm = JSON.parse(await fs.readFile(path.join(npmDir, 'package.json'), 'utf8'));
components.push({
  name: `${npm.name} ${npm.version}`,
  license: npm.license,
  repository: 'https://github.com/sindresorhus/get-east-asian-width',
  source: `https://www.npmjs.com/package/${npm.name}/v/${npm.version}`,
  texts: await Promise.all((await licenseFiles(npmDir)).map(addText)),
});
if (!components.at(-1).texts.length) throw new Error('Missing frontend runtime dependency license');
const intro = `Skylwp third-party license inventory\n\nGenerated by tools/collect-licenses.mjs from the locked Windows dependency graph.\nIncludes build-time dependencies as well as runtime dependencies. No dependency\nsource is modified. The source URL for each crate provides its original source\narchive, including MPL-covered files; project dependencies remain under their\nown licenses. Identical license texts are included once and referenced by SHA-256.\nRust standard-library, MinGW, GCC-runtime and Microsoft SDK notices are also\nprovided in the adjacent licenses directory.\n\n`;
const inventory = components
  .map((p) =>
    [
      p.name,
      `License: ${p.license}`,
      `Repository: ${p.repository ?? ''}`,
      `Original source: ${p.source}`,
      p.note ?? '',
      ...p.texts.map((hash) => `License text: ${hash}`),
    ]
      .filter(Boolean)
      .join('\n'),
  )
  .join('\n\n');
const fullTexts = [...texts]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(
    ([hash, text]) => `\n\n${'='.repeat(72)}\nLICENSE TEXT ${hash}\n${'='.repeat(72)}\n\n${text}`,
  )
  .join('');
await fs.writeFile('docs/THIRD-PARTY-LICENSES.txt', intro + inventory + fullTexts + '\n');
console.log(JSON.stringify({ components: components.length, uniqueLicenseTexts: texts.size }));
