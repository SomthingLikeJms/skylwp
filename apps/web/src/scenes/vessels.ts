import type { BoatKind, Color } from '../world/types';

export interface VesselArt {
  rows: readonly string[];
  width: number;
  height: number;
  hull: Color;
  trim: Color;
  fillFrom: number;
  sail?: boolean;
}
function art(rows: string[], hull: Color, trim: Color, fillFrom: number, sail = false): VesselArt {
  return {
    rows,
    width: Math.max(...rows.map((row) => row.length)),
    height: rows.length,
    hull,
    trim,
    fillFrom,
    sail,
  };
}
