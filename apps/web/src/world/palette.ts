import type { Color } from './types';
import { smooth, mix3 } from './math';
export const SKY: [number, Color, Color][] = [
  [0, [0.012, 0.02, 0.06], [0.05, 0.07, 0.15]],
  [4.5, [0.015, 0.025, 0.07], [0.07, 0.08, 0.17]],
  [6, [0.08, 0.08, 0.2], [0.62, 0.36, 0.33]],
  [7.5, [0.16, 0.25, 0.42], [0.72, 0.6, 0.5]],
  [12, [0.14, 0.29, 0.48], [0.5, 0.64, 0.74]],
  [16.5, [0.15, 0.26, 0.45], [0.6, 0.6, 0.62]],
  [18.3, [0.13, 0.11, 0.3], [0.85, 0.42, 0.3]],
  [19.6, [0.05, 0.05, 0.16], [0.3, 0.16, 0.26]],
  [21, [0.015, 0.022, 0.07], [0.06, 0.08, 0.17]],
  [24, [0.012, 0.02, 0.06], [0.05, 0.07, 0.15]],
];
export function skyColors(h: number) {
  h = ((h % 24) + 24) % 24;
  for (let k = 0; k < SKY.length - 1; k++) {
    const a = SKY[k],
      b = SKY[k + 1];
    if (h >= a[0] && h <= b[0]) {
      const t = smooth(0, 1, (h - a[0]) / (b[0] - a[0]));
      return { top: mix3(a[1], b[1], t), hor: mix3(a[2], b[2], t) };
    }
  }
  return { top: SKY[0][1], hor: SKY[0][2] };
}
